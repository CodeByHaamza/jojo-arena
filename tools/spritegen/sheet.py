"""Assemble a whole sprite sheet (every animation, every view) from a look."""

from __future__ import annotations

from pathlib import Path

import pygame

from .body import body_parts
from .look import Look
from .parts import PART_TYPES
from .raster import CELL, render
from .skeleton import DIRECTIONS, LYING, Pose, animations, make_skeleton

ANCHOR = (24, 44)
GROUND_Y = 45  # bottom row of a body lying on the floor


def draw_frame(look: Look, view: str, frame: Pose | str) -> pygame.Surface:
    if isinstance(frame, str):
        return draw_lying(look, sink=LYING.index(frame))
    sk = make_skeleton(view, frame)
    parts = body_parts(sk, look)
    for spec in look.parts:
        kind = spec["type"]
        if kind not in PART_TYPES:
            raise ValueError(f"{look.id}: unknown part type '{kind}'")
        parts += PART_TYPES[kind](sk, spec, look)
    return render(parts, look.palette)


def draw_lying(look: Look, sink: int) -> pygame.Surface:
    """Knocked out: the standing profile turned on its back, head to the left."""
    standing = draw_frame(look, "right", Pose())
    lying = pygame.transform.rotate(standing, 90)
    box = lying.get_bounding_rect()
    cell = pygame.Surface((CELL, CELL), pygame.SRCALPHA)
    x = CELL // 2 - box.width // 2 - box.x
    y = GROUND_Y + sink - box.bottom
    cell.blit(lying, (x, y))
    return cell


def build_sheet(look: Look) -> tuple[pygame.Surface, str]:
    """The sheet image and its TOML description, in the format the game loads."""
    tables = {view: animations(view) for view in DIRECTIONS}
    names = list(tables["down"])
    max_frames = max(len(entry[3]) for entry in tables["down"].values())
    sheet = pygame.Surface(
        (max_frames * CELL, len(names) * len(DIRECTIONS) * CELL), pygame.SRCALPHA
    )
    lines = [
        f"# {look.name}: generated by tools/make_sprites.py from its look file.",
        "# Edit the look file and regenerate rather than editing this file.",
        f"frame_size = [{CELL}, {CELL}]",
        f"anchor = [{ANCHOR[0]}, {ANCHOR[1]}]",
        'directions = ["down", "up", "right"]',
    ]
    if look.recolor:
        lines += ["", "[recolor]"]
        lines += [f"{slot} = {[list(c) for c in look.palette[slot]]}" for slot in look.recolor]
    for anim_index, name in enumerate(names):
        fps, loop, phases, frames = tables["down"][name]
        row = anim_index * len(DIRECTIONS)
        for dir_index, view in enumerate(DIRECTIONS):
            for frame_index, frame in enumerate(tables[view][name][3]):
                image = draw_frame(look, view, frame)
                sheet.blit(image, (frame_index * CELL, (row + dir_index) * CELL))
        lines += ["", f"[anims.{name}]", f"row = {row}", f"frames = {len(frames)}"]
        lines += [f"fps = {fps}", f"loop = {'true' if loop else 'false'}"]
        if phases:
            lines.append(f"phases = {phases}")
    return sheet, "\n".join(lines) + "\n"


def write_sheet(look: Look, out_dir: Path) -> pygame.Surface:
    sheet, spec = build_sheet(look)
    target = out_dir / look.id
    target.mkdir(parents=True, exist_ok=True)
    pygame.image.save(sheet, str(target / f"{look.id}.png"))
    (target / f"{look.id}.toml").write_text(spec, encoding="utf-8")
    return sheet


def preview(look: Look, sheet: pygame.Surface, scale: int = 3) -> pygame.Surface:
    """A labelled, enlarged contact sheet on a floor-like background, to review a look."""
    from jojo_arena.engine import font

    label_w = 60
    names = list(animations("down"))
    width = label_w + sheet.get_width() * scale
    height = sheet.get_height() * scale
    out = pygame.Surface((width, height))
    out.fill((76, 72, 86))
    for i, name in enumerate(names):
        y = i * len(DIRECTIONS) * CELL * scale
        if i % 2:
            out.fill((70, 66, 80), (0, y, width, len(DIRECTIONS) * CELL * scale))
        font.draw(out, name.upper(), (6, y + 6), (255, 255, 255), scale=2)
    out.blit(pygame.transform.scale_by(sheet, scale), (label_w, 0))
    return out


def portrait(look: Look, scale: int = 4) -> pygame.Surface:
    """Idle front, back and profile side by side, big: the first thing to check."""
    views = [draw_frame(look, view, Pose()) for view in DIRECTIONS]
    out = pygame.Surface((CELL * 3 * scale, CELL * scale))
    out.fill((76, 72, 86))
    for i, image in enumerate(views):
        out.blit(pygame.transform.scale_by(image, scale), (i * CELL * scale, 0))
    return out
